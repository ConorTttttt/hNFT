<script lang="ts">
  import type { ActionHash } from "@holochain/client";
  import { useAppState } from "$lib/appState.svelte";
  import { toHex } from "$lib/format";

  let {
    open = $bindable(false),
    batch,
    onreserved,
  }: {
    open: boolean;
    batch: ActionHash;
    /** Fires once the purchase is on-chain, so the caller can chain into
     * the existing Unyt payment dialog with `nftId = purchase hash`. */
    onreserved?: (purchase: ActionHash) => void;
  } = $props();

  const app = useAppState();
  let dlg = $state<HTMLDialogElement>();
  let busy = $state(false);

  $effect(() => {
    if (open) dlg?.showModal();
    else dlg?.close();
  });

  async function submit() {
    busy = true;
    try {
      // The nonce is generated AND encrypted to the minter's key entirely
      // inside `reserve_blind_purchase` (HDK's random_bytes +
      // x_25519_x_salsa20_poly1305_encrypt) — this dialog supplies nothing
      // but the batch. `buyerNonce` comes BACK from the zome call; it's
      // never generated client-side.
      const out = await app.reserveBlindPurchase(batch);
      if (out) {
        // No on-chain way to recover this later — the buyer's own client
        // must hold onto it to confirm the eventual reveal matches what
        // they committed to. sessionStorage is a demo-only stand-in; see
        // docs/blind-box-collections.md's UI-storage note.
        sessionStorage.setItem(
          `blind-nonce:${toHex(out.purchase)}`,
          toHex(out.buyerNonce),
        );
        open = false;
        onreserved?.(out.purchase);
      }
    } finally {
      busy = false;
    }
  }
</script>

<dialog bind:this={dlg} onclose={() => (open = false)}>
  <div class="stack" style="min-width: min(420px, 88vw)">
    <h3>Buy blind</h3>
    <p class="faint small">
      You won't know which item you receive until the seller resolves your
      purchase. Your own secret commitment — generated by the zome call, on
      this device's behalf — is part of what makes the assignment fair to
      you: neither the minter nor a colluding buyer can predict it before
      you commit.
    </p>
    <div class="row between">
      <button class="ghost" onclick={() => (open = false)} disabled={busy}>Cancel</button>
      <button class="primary" onclick={submit} disabled={busy}>
        {busy ? "Reserving…" : "Reserve & continue to payment"}
      </button>
    </div>
  </div>
</dialog>
