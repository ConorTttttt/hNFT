//! Blind-box collection sweettests. See `blind_collection.rs`'s DESIGN.md
//! for the mechanism and `HANDOFF.md` for what's covered here vs. left as
//! follow-up.
//!
//! **Known test gap:** DESIGN.md's own priority list calls for adversarial
//! tests -- (a) colluding minter+buyer pre-purchase prediction, (b) a
//! minter post-nonce withholding a reveal -- neither is in this pass.
//! Both need a way to author a raw, off-protocol entry (a
//! `BlindAssignmentReveal` or `TransferCommitment` bypassing
//! `resolve_blind_assignment_from_rave`'s own bookkeeping) to simulate a
//! misbehaving minter, which this demo's coordinator API doesn't expose.
//! Flagging as a known gap rather than skipping silently, per HANDOFF.md.
//!
//! **Also not covered here:** a genuine two-party (separate buyer/minter
//! cell) flow. `reserve_blind_purchase` encrypts to the collection's own
//! `minter_x25519_pubkey`, which only exists once baked into that
//! specific DNA's properties -- a real cross-agent test needs the buyer
//! joined to the SAME DNA hash the minter's blind props were built with
//! (i.e. both agents in `setup_app`'s cell list, not two independent
//! `setup()` calls each getting their own DNA). These tests instead use a
//! second agent joined to the minter's own app for the buyer role, which
//! exercises the same validate() paths (buyer-authored purchase, minter-
//! authored reveal, buyer-bound transfer) without standing up Unyt.

use holochain::prelude::*;
use holochain::sweettest::*;
use nft::blind::{
    MintBlindBatchInput, MintBlindBatchOutput, ReserveBlindPurchaseInput,
    ReserveBlindPurchaseOutput, ResolveBlindAssignmentInput, ResolveBlindAssignmentOutput,
};
use nft::transfer::CommitmentRef;
use nft_integrity::*;

mod common;
use common::*;

/// Installs a bootstrap app (to generate the minter's X25519 keypair in
/// their own conductor's lair), then the real blind-enabled app for a
/// second agent -- the buyer -- joined to the SAME DNA (so both agents'
/// validate() calls agree on `minter_x25519_pubkey`/`blind_resolution_window_secs`).
/// Two installs are required because the key must exist in lair BEFORE the
/// DNA that references it (part of the DNA hash, via `modifiers.properties`)
/// can be built -- same chicken-and-egg `max_supply_cap_is_enforced...` in
/// `flows.rs` already solves for `minter_pubkey`, one step further because
/// the X25519 key itself must be *generated by a zome call*, not just known
/// upfront.
async fn setup_blind_collection(
    max_supply: u32,
    transfer_window_secs: u64,
    blind_resolution_window_secs: u64,
) -> (SweetConductor, Vec<SweetCell>, AgentPubKey, AgentPubKey) {
    let mut conductor = SweetConductor::standard().await;
    let minter = SweetAgents::one(conductor.keystore()).await;

    // Bootstrap app: no blind props needed yet, just a cell so the minter
    // can call `generate_minter_x25519_pubkey` in their own conductor.
    let bootstrap_dna =
        dna(Some(dev_props(Some(minter.clone()), max_supply, transfer_window_secs))).await;
    let bootstrap_app = conductor
        .setup_app_for_agent("nft-bootstrap", minter.clone(), &[bootstrap_dna])
        .await
        .unwrap();
    let bootstrap_zome = bootstrap_app.cells()[0].zome(ZOME);
    let pubkey_hex: String = conductor
        .call(&bootstrap_zome, "generate_minter_x25519_pubkey", ())
        .await;

    // Real app: same conductor/keystore (so the just-generated X25519
    // secret is available), now with the key baked into properties. Buyer
    // joins the SAME dna hash so both agents' validate() calls agree on it.
    let real_dna = dna(Some(dev_props_blind(
        Some(minter.clone()),
        max_supply,
        transfer_window_secs,
        blind_resolution_window_secs,
        pubkey_hex,
    )))
    .await;

    let minter_app = conductor
        .setup_app_for_agent("nft-blind-minter", minter.clone(), &[real_dna.clone()])
        .await
        .unwrap();
    let minter_cell = minter_app.cells()[0].clone();

    let buyer = SweetAgents::one(conductor.keystore()).await;
    let buyer_app = conductor
        .setup_app_for_agent("nft-blind-buyer", buyer.clone(), &[real_dna])
        .await
        .unwrap();
    let buyer_cell = buyer_app.cells()[0].clone();

    (conductor, vec![minter_cell, buyer_cell], minter, buyer)
}

#[tokio::test(flavor = "multi_thread")]
async fn blind_box_happy_path_mint_purchase_resolve_transfer() {
    let (conductor, cells, minter_key, buyer_key) = setup_blind_collection(0, 300, 300).await;
    let minter_zome = cells[0].zome(ZOME);
    let buyer_zome = cells[1].zome(ZOME);

    let mint_seed = [42u8; 32];
    let batch: MintBlindBatchOutput = conductor
        .call(
            &minter_zome,
            "mint_blind_batch",
            MintBlindBatchInput {
                metadata_hashes: vec![metadata_hash(1), metadata_hash(2), metadata_hash(3)],
                mint_seed,
            },
        )
        .await;
    assert_eq!(batch.nfts.len(), 3);
    await_consistency(&cells).await.unwrap();

    for nft in &batch.nfts {
        let rec: Option<Record> = conductor.call(&minter_zome, "get_nft", nft.clone()).await;
        let manifest = NftManifest::try_from(rec.unwrap()).unwrap();
        assert!(matches!(manifest.payload, NftPayload::Sealed));
        assert_eq!(manifest.batch, Some(batch.batch.clone()));
    }

    // Buyer reserves a purchase.
    let purchase: ReserveBlindPurchaseOutput = conductor
        .call(
            &buyer_zome,
            "reserve_blind_purchase",
            ReserveBlindPurchaseInput {
                batch: batch.batch.clone(),
            },
        )
        .await;
    await_consistency(&cells).await.unwrap();

    // Minter resolves it under a claimed (demo-mode, unverified) Unyt settlement.
    let resolved: ResolveBlindAssignmentOutput = conductor
        .call(
            &minter_zome,
            "resolve_blind_assignment_from_rave",
            ResolveBlindAssignmentInput {
                purchase: purchase.purchase.clone(),
                mint_seed,
                rave: purchase.purchase.clone(),
                fulfilled: true,
                nft_id: purchase.purchase.to_string(),
                new_owner: buyer_key.to_string(),
                previous_owner: minter_key.to_string(),
            },
        )
        .await;
    assert!(batch.nfts.contains(&resolved.assigned_nft));
    await_consistency(&cells).await.unwrap();

    // Buyer accepts the resulting transfer offer.
    let _receipt: Record = conductor
        .call(
            &buyer_zome,
            "accept_transfer",
            CommitmentRef {
                commitment: resolved.commitment.clone(),
            },
        )
        .await;
    await_consistency(&cells).await.unwrap();

    let owner: AgentPubKey = conductor
        .call(&buyer_zome, "current_owner", resolved.assigned_nft.clone())
        .await;
    assert_eq!(owner, buyer_key, "the resolved NFT must end up owned by the paying buyer");
}

#[tokio::test(flavor = "multi_thread")]
async fn duplicate_purchase_assignment_is_rejected() {
    let (conductor, cells, minter_key, buyer_key) = setup_blind_collection(0, 300, 300).await;
    let minter_zome = cells[0].zome(ZOME);
    let buyer_zome = cells[1].zome(ZOME);

    let mint_seed = [7u8; 32];
    let batch: MintBlindBatchOutput = conductor
        .call(
            &minter_zome,
            "mint_blind_batch",
            MintBlindBatchInput {
                metadata_hashes: vec![metadata_hash(1), metadata_hash(2)],
                mint_seed,
            },
        )
        .await;
    await_consistency(&cells).await.unwrap();

    let purchase: ReserveBlindPurchaseOutput = conductor
        .call(
            &buyer_zome,
            "reserve_blind_purchase",
            ReserveBlindPurchaseInput { batch: batch.batch.clone() },
        )
        .await;
    await_consistency(&cells).await.unwrap();

    let resolve_input = ResolveBlindAssignmentInput {
        purchase: purchase.purchase.clone(),
        mint_seed,
        rave: purchase.purchase.clone(),
        fulfilled: true,
        nft_id: purchase.purchase.to_string(),
        new_owner: buyer_key.to_string(),
        previous_owner: minter_key.to_string(),
    };

    let _first: ResolveBlindAssignmentOutput = conductor
        .call(&minter_zome, "resolve_blind_assignment_from_rave", resolve_input.clone())
        .await;

    let second: Result<ResolveBlindAssignmentOutput, _> = conductor
        .call_fallible(&minter_zome, "resolve_blind_assignment_from_rave", resolve_input)
        .await;
    assert!(second.is_err(), "the same purchase must not be assignable twice");
}

#[tokio::test(flavor = "multi_thread")]
async fn fully_assigned_batch_rejects_further_resolution() {
    let (conductor, cells, minter_key, buyer_key) = setup_blind_collection(0, 300, 300).await;
    let minter_zome = cells[0].zome(ZOME);
    let buyer_zome = cells[1].zome(ZOME);

    let mint_seed = [9u8; 32];
    // A single-slot batch: the first purchase takes the only slot.
    let batch: MintBlindBatchOutput = conductor
        .call(
            &minter_zome,
            "mint_blind_batch",
            MintBlindBatchInput {
                metadata_hashes: vec![metadata_hash(1)],
                mint_seed,
            },
        )
        .await;
    await_consistency(&cells).await.unwrap();

    let p1: ReserveBlindPurchaseOutput = conductor
        .call(&buyer_zome, "reserve_blind_purchase", ReserveBlindPurchaseInput { batch: batch.batch.clone() })
        .await;
    await_consistency(&cells).await.unwrap();
    let _r1: ResolveBlindAssignmentOutput = conductor
        .call(
            &minter_zome,
            "resolve_blind_assignment_from_rave",
            ResolveBlindAssignmentInput {
                purchase: p1.purchase.clone(),
                mint_seed,
                rave: p1.purchase.clone(),
                fulfilled: true,
                nft_id: p1.purchase.to_string(),
                new_owner: buyer_key.to_string(),
                previous_owner: minter_key.to_string(),
            },
        )
        .await;
    await_consistency(&cells).await.unwrap();

    // A second purchase against the same, now-exhausted batch.
    let p2: ReserveBlindPurchaseOutput = conductor
        .call(&buyer_zome, "reserve_blind_purchase", ReserveBlindPurchaseInput { batch: batch.batch.clone() })
        .await;
    await_consistency(&cells).await.unwrap();
    let r2: Result<ResolveBlindAssignmentOutput, _> = conductor
        .call_fallible(
            &minter_zome,
            "resolve_blind_assignment_from_rave",
            ResolveBlindAssignmentInput {
                purchase: p2.purchase.clone(),
                mint_seed,
                rave: p2.purchase.clone(),
                fulfilled: true,
                nft_id: p2.purchase.to_string(),
                new_owner: buyer_key.to_string(),
                previous_owner: minter_key.to_string(),
            },
        )
        .await;
    assert!(r2.is_err(), "resolving against a fully-assigned batch must fail");
}
